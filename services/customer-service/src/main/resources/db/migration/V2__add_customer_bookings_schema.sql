CREATE TABLE public.customer_bookings (
      id bigint NOT NULL,
      customer_username character varying(255),
      registration_id character varying(255),
      event_id bigint NOT NULL,
      order_id character varying(255) NOT NULL,
      booking_status character varying(255),
      created_at timestamp(6) with time zone NOT NULL,
      updated_at timestamp(6) with time zone NOT NULL,

      CONSTRAINT customer_bookings_pkey PRIMARY KEY (id),
      CONSTRAINT customer_bookings_booking_status_check CHECK (booking_status IN ('PENDING', 'CONFIRMED', 'CANCELLED')),
      CONSTRAINT customer_bookings_registration_id_key UNIQUE (registration_id)
);

ALTER TABLE public.customer_bookings ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY (
    SEQUENCE NAME public.customer_bookings_id_seq
    START WITH 1
    INCREMENT BY 1
    NO MINVALUE
    NO MAXVALUE
    CACHE 1
);
